import type { Metadata } from "next";
import Link from "next/link";
import { requireProject } from "@/lib/session";
import { db } from "@/lib/db";
import { generateBrief, listBriefs, type BriefFinding, listActivationDefinitions } from "@retainos/analytics";
import { entitlementFor } from "@retainos/database";
import {
  PageHeader, Card, CardHeader, CardBody, Badge, Empty, Caveats, Button, Metric,
} from "@/components/ui";
import { when } from "@/lib/format";
import { SaveBriefButton } from "./actions-client";

export const metadata: Metadata = { title: "Command centre" };
export const dynamic = "force-dynamic";

const CONFIDENCE_TONE = {
  measured: "good",
  qualified: "info",
  uncertain: "warn",
} as const;

function Finding({ finding }: { finding: BriefFinding }) {
  return (
    <li className="border-b border-navy-800/80 py-3 last:border-0 last:pb-0">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <p className="min-w-0 text-sm font-medium leading-snug text-offwhite">{finding.statement}</p>
        <Badge tone={CONFIDENCE_TONE[finding.confidence]}>{finding.confidence}</Badge>
      </div>
      <ul className="mt-2 space-y-1">
        {finding.evidence.map((e, i) => (
          <li key={i} className="flex gap-2 text-xs leading-relaxed text-slate-400">
            <span aria-hidden className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-slate-600" />
            <span>{e}</span>
          </li>
        ))}
      </ul>
      {finding.nextStep ? (
        <p className="mt-2 text-xs leading-relaxed text-cyan-400/90">
          <span className="font-medium">Next:</span> {finding.nextStep}
        </p>
      ) : null}
    </li>
  );
}

export default async function CommandCentre() {
  const ctx = await requireProject();
  const handle = db();
  const entitlement = entitlementFor(handle, ctx.org.id);

  if (!entitlement.features.commandCenter) {
    return (
      <>
        <PageHeader title="Command centre" />
        <Empty
          title="Not included on your plan"
          body={`The command centre is part of the Starter plan and above. You are on ${entitlement.planId}.`}
          action={<Link href="/settings/billing"><Button>See plans</Button></Link>}
        />
      </>
    );
  }

  const definitions = listActivationDefinitions(handle, ctx.project.id);
  const activationEvent = (definitions.find((d) => d.isPrimary) ?? definitions[0])?.activationEvent;
  const brief = generateBrief(handle, ctx.project.id, {
    timezone: ctx.project.timezone,
    activationEvent,
  });
  const saved = listBriefs(handle, ctx.project.id, 5);

  const counts = {
    findings: brief.sections.reduce((s, section) => s + section.findings.length, 0),
    unknowns: brief.unknowns.length,
  };

  return (
    <>
      <PageHeader
        title="Command centre"
        description="What changed, what it means, what is not known, and what to do first. Built from local rules — no model, no key, no network — so every sentence traces to a query."
        action={<SaveBriefButton />}
      />

      <div className="mb-5 rounded-xl border border-navy-700/70 bg-gradient-to-br from-navy-900/80 to-navy-900/40 px-5 py-4">
        <p className="text-sm font-medium leading-relaxed text-offwhite">{brief.headline}</p>
        <p className="mt-1.5 text-xs text-slate-500">
          Week of {when(brief.periodStart)} to {when(brief.periodEnd)} · generated by {brief.generator}
        </p>
      </div>

      <div className="mb-5 grid gap-4 sm:grid-cols-3">
        <Metric
          label="Findings this week"
          value={counts.findings}
          definition="Statements the data supports, across every section of the brief."
        />
        <Metric
          label="Open unknowns"
          value={counts.unknowns}
          definition="Questions this brief cannot answer, carried rather than quietly dropped."
        />
        <Metric
          label="Saved briefs"
          value={saved.length}
          definition="Briefs kept for the record, so a past week's reading can be checked against what happened."
        />
      </div>

      <div className="space-y-5">
        {brief.sections.map((section) => (
          <Card key={section.id}>
            <CardHeader
              title={section.title}
              action={
                section.findings.length > 0
                  ? <Badge tone="neutral">{section.findings.length}</Badge>
                  : <Badge tone="good">clear</Badge>
              }
            />
            <CardBody>
              {section.findings.length === 0 ? (
                <p className="text-xs leading-relaxed text-slate-400">{section.emptyNote}</p>
              ) : (
                <ul>
                  {section.findings.map((finding, i) => <Finding key={i} finding={finding} />)}
                </ul>
              )}
            </CardBody>
          </Card>
        ))}

        {brief.unknowns.length > 0 ? (
          <Card>
            <CardHeader
              title="What this brief cannot tell you"
              subtitle="Carried deliberately. A report with holes in it beats one a founder cannot trust."
            />
            <CardBody>
              <Caveats items={brief.unknowns} tone="info" />
            </CardBody>
          </Card>
        ) : null}

        <Card>
          <CardHeader title="How to read the numbers above" />
          <CardBody>
            <Caveats items={brief.disclaimers} tone="info" />
          </CardBody>
        </Card>

        {saved.length > 0 ? (
          <Card>
            <CardHeader title="Saved briefs" subtitle="Kept so last week's reading can be checked against what happened." />
            <CardBody>
              <ul className="space-y-1.5">
                {saved.map((b) => (
                  <li key={b.id} className="flex items-center justify-between gap-3 text-xs text-slate-400">
                    <span>{when(b.period_start)} – {when(b.period_end)}</span>
                    <span className="text-slate-600">saved {when(b.created_at)}</span>
                  </li>
                ))}
              </ul>
            </CardBody>
          </Card>
        ) : null}
      </div>
    </>
  );
}
